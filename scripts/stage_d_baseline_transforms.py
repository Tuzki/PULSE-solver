#!/usr/bin/env python3
"""Apply conservative integrated Stage D candidate edits to an *existing* Stage C checkout.

No topology-specific branches. Stop rather than guessing when anchors do not match.
Generated by ChatGPT using the Stage C GitHub source excerpts of 2026-11-04.
This script has not been compiled against the full PULSE repository in this environment.
"""
import argparse
import hashlib
import json
import pathlib
import sys

REQUIRED_FILES = [
    'include/pulse/core.hpp', 'src/semantics.cpp', 'src/descriptor.cpp',
    'src/engineering_flow.cpp', 'src/pevt.cpp',
]


def replace_once(source: str, before: str, after: str, label: str) -> str:
    count = source.count(before)
    if count != 1:
        raise ValueError(f'{label}: expected exactly one anchor, found {count}. File untouched.')
    return source.replace(before, after, 1)


def transform(files):
    result = {name: text.replace('\r\n', '\n') for name, text in files.items()}

    # D-COMPILER: part ids are invariant for one frozen Model.
    name = 'include/pulse/core.hpp'
    result[name] = replace_once(result[name],
        '  std::vector<Part> parts;\n  std::map<std::string, Signal> signals;',
        '  std::vector<Part> parts;\n'
        '  // D: Frozen once at Model compilation; reusable by every modal bind.\n'
        '  std::map<std::string, int> compiled_part_index;\n'
        '  std::map<std::string, Signal> signals;',
        'compiled-index declaration')

    name = 'src/semantics.cpp'
    result[name] = replace_once(result[name],
        '        std::sort(m.registry.begin(), m.registry.end());\n'
        '        m.compile_seconds =',
        '        std::sort(m.registry.begin(), m.registry.end());\n'
        '        // D: Resolve part identities once after validating the complete model.\n'
        '        for (size_t i = 0; i < m.parts.size(); ++i)\n'
        '            m.compiled_part_index.emplace(m.parts[i].raw.id, int(i));\n'
        '        require(m.compiled_part_index.size() == m.parts.size(), 12,\n'
        '                "INTERNAL_ERROR", "compiled part index not injective");\n'
        '        m.compile_seconds =',
        'static index construction')

    name = 'src/descriptor.cpp'
    s = result[name]
    s = replace_once(s,
        '    std::map<std::string, int> partidx;\n',
        '    const std::map<std::string, int> &partidx;\n',
        'frozen index reference')
    s = replace_once(s,
        '        : m(mm), regs(rr), bits(std::move(bb)), segments(std::move(ss)) {\n'
        '        if(!equations){for(size_t i=0;i<m.parts.size();++i)partidx[m.parts[i].raw.id]=int(i);return;}\n',
        '        : m(mm), regs(rr), bits(std::move(bb)), segments(std::move(ss)),\n'
        '          partidx(mm.compiled_part_index) {\n'
        '        if (!equations) return;\n',
        'Assembler fast-path index')
    s = replace_once(s,
        '        for (size_t i = 0; i < m.parts.size(); ++i)\n'
        '            partidx[m.parts[i].raw.id] = int(i);\n',
        '        // partidx is already compiled into the frozen Model.\n',
        'Assembler full-build index')

    # D-BINDING: eliminate repeated heap construction of big N, B and scale buffers.
    s = replace_once(s,
        '    const auto &binding=*stored.observer_binding;Matrix N=binding.N,B=binding.B;\n',
        '    const auto &binding=*stored.observer_binding;\n'
        '    // D: Per-thread scratch is entirely overwritten before every use.\n'
        '    // It is not shared with a Mode, transaction or persistent cache.\n'
        '    struct BindingScratch { Matrix N, B, scale; };\n'
        '    static thread_local BindingScratch scratch;\n'
        '    Matrix &N=scratch.N, &B=scratch.B;\n'
        '    N=binding.N; B=binding.B;\n',
        'binding matrix scratch')
    s = replace_once(s,
        '    Matrix scale=Matrix::Zero(mode.binding.read().residual_map.rows(),m.ns+1);\n',
        '    Matrix &scale=scratch.scale;\n'
        '    scale=Matrix::Zero(mode.binding.read().residual_map.rows(),m.ns+1);\n',
        'binding scale scratch')
    result[name] = s

    # D-FLOW: the projection only needs the original definition + one guard.
    # A fresh ModeBinding is constructed instead of detaching/copying maps and all guards.
    name = 'src/engineering_flow.cpp'
    result[name] = replace_once(result[name],
        '    Mode view=data_->mode;view.binding.edit().maps.clear();view.bools.clear();\n'
        '    view.binding.edit().guards.clear();view.binding.edit().guards.push_back({row,0,1,"OBSERVE"});\n',
        '    // D: Use one lightweight projection Mode; never clone the parent binding.\n'
        '    Mode view;\n'
        '    view.definition=data_->mode.definition;\n'
        '    view.numerical_strategy=data_->mode.numerical_strategy;\n'
        '    view.binding.edit().guards.push_back({row,0,1,"OBSERVE"});\n',
        'minimal flow projection')

    # D-ARCHIVE: these tables are used as key->id lookups only; they are never
    # iterated to determine PEVT order. The IDs still come from append order.
    name = 'src/pevt.cpp'
    s = result[name]
    s = replace_once(s,
        '#include <deque>\n', '#include <deque>\n#include <unordered_map>\n',
        'archive unordered_map include')
    s = replace_once(s,
        '  std::map<std::string,uint32_t> component_ids,signal_ids,block_ids,value_ids,definition_ids,instance_ids,state_ids,component_mode_ids;\n',
        '  // D: O(1) average associative lookup; ID assignment remains append-ordered.\n'
        '  std::unordered_map<std::string,uint32_t> component_ids,signal_ids,block_ids,value_ids,\n'
        '      definition_ids,instance_ids,state_ids,component_mode_ids;\n',
        'archive lookup table')
    result[name] = s
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=pathlib.Path, required=True,
                        help='EXISTING Stage C checkout; edited in place ONLY after strict anchor audit')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--manifest', type=pathlib.Path)
    args = parser.parse_args()
    repo = args.repo.resolve()
    files = {}
    for p in REQUIRED_FILES:
        path = repo/p
        if not path.is_file():
            raise SystemExit(f'MISSING {path}: cannot patch incomplete PULSE source')
        files[p] = path.read_text(encoding='utf-8')
    try:
        changed = transform(files)
    except ValueError as exc:
        raise SystemExit(f'ANCHOR REFUSED: {exc}')
    audit = {'status':'ANCHOR_VERIFIED_ONLY_NOT_COMPILED',
             'base_expected':'performance/stage-c-20261103 (fa2bc5e)',
             'files':{p:{'before_sha256':hashlib.sha256(files[p].encode()).hexdigest(),
                         'after_sha256':hashlib.sha256(changed[p].encode()).hexdigest(),
                         'modified':files[p].replace('\r\n','\n')!=changed[p]}
                      for p in REQUIRED_FILES}}
    if not args.dry_run:
        for p in REQUIRED_FILES:
            (repo/p).write_text(changed[p],encoding='utf-8',newline='\n')
        audit['status']='WRITTEN_NOT_COMPILED_NOT_VALIDATED'
    if args.manifest:
        args.manifest.parent.mkdir(parents=True,exist_ok=True)
        args.manifest.write_text(json.dumps(audit,indent=2)+'\n')
    print(json.dumps(audit,indent=2))

if __name__ == '__main__':
    main()
